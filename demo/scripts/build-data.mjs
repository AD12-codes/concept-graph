// Pre-renders the demo's concept data from ../examples/typeninja.json so the
// video needs no highlighter at render time. Run: node scripts/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { codeToHtml } from "shiki";

const file = JSON.parse(readFileSync(new URL("../../examples/typeninja.json", import.meta.url), "utf-8"));
const PICKS = [
  "security/server-side-result-validation",
  "state-management/typing-engine",
  "rate-limiting/fixed-window-limiters",
];

const categories = [...new Set(file.nodes.map((n) => n.id.split("/")[0]))];
const LABELS = {
  security: "Security", auth: "Auth", "rate-limiting": "Rate limiting", "state-management": "State management",
  database: "Database", communication: "Communication", networking: "Networking", "api-design": "API design",
  "system-design": "System design", "ui-components": "UI components", "programming-languages": "Programming languages",
  performance: "Performance", testing: "Testing", devops: "DevOps", tooling: "Tooling",
};

const picked = [];
for (const id of PICKS) {
  const node = file.nodes.find((n) => n.id === id);
  const snippet = node.code[0];
  const html = await codeToHtml(snippet.snippet, { lang: snippet.lang, theme: "github-dark" });
  picked.push({
    id, title: node.title, summary: node.summary, category: id.split("/")[0],
    explanation: node.explanation,
    snippet: { file: snippet.file, lines: snippet.lines, note: snippet.note, html, lineCount: snippet.snippet.split("\n").length },
  });
}

const out = {
  project: file.project, name: file.name, generatedAt: file.generatedAt, commit: file.commit,
  nodeCount: file.nodes.length,
  categories: categories.map((id) => ({ id, label: LABELS[id], count: file.nodes.filter((n) => n.id.startsWith(id + "/")).length,
    nodes: file.nodes.filter((n) => n.id.split("/").length === 2 && n.id.startsWith(id + "/")).map((n) => ({ id: n.id, title: n.title })) })),
  picked,
  rawJson: JSON.stringify({ ...file, nodes: [ { ...file.nodes.find(n=>n.id===PICKS[0]), code: [ { ...file.nodes.find(n=>n.id===PICKS[0]).code[0], snippet: file.nodes.find(n=>n.id===PICKS[0]).code[0].snippet.split("\n").slice(0, 8).join("\n") + "\n  // …" } ], explanation: file.nodes.find(n=>n.id===PICKS[0]).explanation.slice(0, 118) + " …" } ] }, null, 2),
};
writeFileSync(new URL("../src/data/graph.ts", import.meta.url),
  `// Generated by scripts/build-data.mjs. Do not edit.\nexport const GRAPH = ${JSON.stringify(out, null, 2)} as const;\n`);
console.log("wrote src/data/graph.ts", picked.map((p) => p.id).join(", "));
